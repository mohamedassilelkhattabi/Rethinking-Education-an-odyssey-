import {
  Anchor,
  Cable,
  Carrot,
  Cherry,
  Clock,
  Coins,
  Compass,
  Droplets,
  Fish,
  FlaskConical,
  Hourglass,
  Lamp,
  Lock,
  Map as MapIcon,
  Mountain,
  MountainSnow,
  Package,
  Pickaxe,
  Sailboat,
  Scale,
  Shield,
  Skull,
  Store,
  Trees,
  Trophy,
  Users,
  VenetianMask,
  Waves,
  Wheat,
  type LucideIcon,
} from 'lucide-react';

const REGISTRY: Record<string, LucideIcon> = {
  anchor: Anchor,
  berries: Cherry,
  cave: Mountain,
  cliff: MountainSnow,
  clock: Clock,
  coast: Waves,
  coins: Coins,
  compass: Compass,
  fish: Fish,
  forest: Trees,
  hourglass: Hourglass,
  lantern: Lamp,
  lock: Lock,
  map: MapIcon,
  mask: VenetianMask,
  medicine: FlaskConical,
  merchant: Wheat,
  mountain: Mountain,
  package: Package,
  pickaxe: Pickaxe,
  roots: Carrot,
  rope: Cable,
  sail: Sailboat,
  scale: Scale,
  shield: Shield,
  skull: Skull,
  store: Store,
  trophy: Trophy,
  users: Users,
  water: Droplets,
  wheat: Wheat,
};

export function GameIcon({ name, className, strokeWidth = 1.75 }: { name: string; className?: string; strokeWidth?: number }) {
  const Icon = REGISTRY[name] ?? Compass;
  return <Icon className={className} strokeWidth={strokeWidth} aria-hidden="true" />;
}
